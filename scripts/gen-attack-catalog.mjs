// Generates the attack catalog consumed by the Go API and the MCP server from the single source of
// truth, client/src/data/attacks.js.
//
// The catalog exists because "a Spoofing result may only cite a Spoofing attack" is an invariant the
// dropdown enforces by construction but the API and MCP cannot see: they would otherwise accept any
// string. Hand-copying 27 ids into two more languages guarantees drift, so both are generated and a
// test re-runs this to prove they still match.
//
// Usage:  node scripts/gen-attack-catalog.mjs [--check]
//   --check exits non-zero if the generated files are stale instead of rewriting them.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'client', 'src', 'data', 'attacks.js');
const GO_OUT = join(ROOT, 'server', 'utils', 'attackCatalog.go');
const MCP_OUT = join(ROOT, 'docker', 'mcp-server', 'src', 'data', 'attackCatalog.json');

// attacks.js is plain data with ES module syntax. Stripping the export keywords makes it evaluable
// without a bundler, which keeps this script dependency free.
const source = readFileSync(SRC, 'utf8')
  .replace(/^export const /gm, 'const ')
  .replace(/^export function /gm, 'function ');

const context = { module: { exports: {} } };
vm.createContext(context);
vm.runInContext(`${source}\nmodule.exports = { attacks, STRIDE_LABELS };`, context);
const { attacks, STRIDE_LABELS } = context.module.exports;

const CATEGORIES = Object.keys(STRIDE_LABELS);

const catalog = attacks
  .map((a) => ({
    id: a.id,
    name: a.name,
    categories: CATEGORIES.filter((c) => a.stride && a.stride[c]),
  }))
  .sort((a, b) => a.id.localeCompare(b.id));

for (const a of catalog) {
  if (!a.id || !a.name) throw new Error(`attack missing id or name: ${JSON.stringify(a)}`);
  if (!a.categories.length) throw new Error(`attack ${a.id} declares no STRIDE category`);
}

// ---- Go ----
const goLines = [];
goLines.push('// Code generated by scripts/gen-attack-catalog.mjs. DO NOT EDIT.');
goLines.push('//');
goLines.push('// Source of truth: client/src/data/attacks.js. Regenerate with');
goLines.push('//   node scripts/gen-attack-catalog.mjs');
goLines.push('');
goLines.push('package utils');
goLines.push('');
goLines.push('// AttackNames maps each attack id to its display name.');
goLines.push('var AttackNames = map[string]string{');
for (const a of catalog) goLines.push(`\t${JSON.stringify(a.id)}: ${JSON.stringify(a.name)},`);
goLines.push('}');
goLines.push('');
goLines.push('// AttackCategories lists the STRIDE categories each attack can be weaponized to achieve.');
goLines.push('// A threat may only cite an attack that covers the threat\'s own category.');
goLines.push('var AttackCategories = map[string][]string{');
for (const a of catalog) {
  goLines.push(`\t${JSON.stringify(a.id)}: {${a.categories.map((c) => JSON.stringify(c)).join(', ')}},`);
}
goLines.push('}');
goLines.push('');
goLines.push('// IsValidAttackForCategory reports whether attackID is a known attack that is weaponized');
goLines.push('// to achieve category. An empty attackID is not valid: callers that allow "not yet tied to');
goLines.push('// an attack" must check for empty themselves, so the permission is explicit at each site.');
goLines.push('func IsValidAttackForCategory(attackID, category string) bool {');
goLines.push('\tfor _, c := range AttackCategories[attackID] {');
goLines.push('\t\tif c == category {');
goLines.push('\t\t\treturn true');
goLines.push('\t\t}');
goLines.push('\t}');
goLines.push('\treturn false');
goLines.push('}');
goLines.push('');
const goText = goLines.join('\n');

// ---- MCP ----
const mcpText = `${JSON.stringify({ generatedBy: 'scripts/gen-attack-catalog.mjs', attacks: catalog }, null, 2)}\n`;

const check = process.argv.includes('--check');
let stale = false;
for (const [path, text] of [[GO_OUT, goText], [MCP_OUT, mcpText]]) {
  let current = null;
  try { current = readFileSync(path, 'utf8'); } catch { /* not generated yet */ }
  if (current === text) continue;
  stale = true;
  if (check) {
    console.error(`STALE: ${path}`);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
    console.log(`wrote ${path}`);
  }
}

if (check && stale) {
  console.error('\nattacks.js changed without regenerating. Run: node scripts/gen-attack-catalog.mjs');
  process.exit(1);
}
if (!stale) console.log('catalog up to date');
console.log(`${catalog.length} attacks; categories covered: ${
  CATEGORIES.filter((c) => catalog.some((a) => a.categories.includes(c))).length}/${CATEGORIES.length}`);
